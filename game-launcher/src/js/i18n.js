export function t(key, lang = 'vi', params = {}) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.vi;
  let text = dict[key] || TRANSLATIONS.vi[key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replaceAll(`{${k}}`, v);
  }
  return text;
}

export function applyI18n(lang = 'vi') {
  if (typeof document === 'undefined') return;
  if (document.documentElement) document.documentElement.lang = lang;
  if (typeof document.querySelectorAll !== 'function') return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key, lang);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = t(key, lang);
  });
}

// The plain-words message for an error (R17). Detail goes to the console, never to the player.
export function errorText(err, lang = 'vi') {
  const key = err?.key && TRANSLATIONS.vi[err.key] ? err.key : 'err_generic';
  return t(key, lang);
}
